//! Recibos de salário dos países adaptados na rodada 2 (docs/international.md): os rótulos de
//! cada um (sem acentos, em minúsculas) e o formato dos números. O leitor é o mesmo dos outros
//! (`payslip`); aqui ficam só os dados.

/// Como o documento escreve os números.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Num {
    /// 1,234.56 (Reino Unido, Canadá).
    Dot,
    /// 1.234,56 ou 1 234,56 (França, Alemanha, Argentina).
    Comma,
    /// 1.234.567, sem centavos (Chile).
    Int,
}

#[derive(Debug, PartialEq, Eq)]
pub struct Spec {
    pub country: &'static str,
    pub num: Num,
    /// Rótulos que dão o país: pelo menos dois (ou um de `strong`).
    pub detect: &'static [&'static str],
    pub strong: &'static [&'static str],
    /// Colunas do período e do ano (vale a penúltima), sem código de verba na frente.
    pub ytd_column: bool,
    pub summary: &'static [&'static str],
    pub deductions: &'static [&'static str],
    pub gross: &'static [&'static str],
    pub ded_total: &'static [&'static str],
    pub net: &'static [&'static str],
    pub contribution: &'static [&'static str],
    pub contribution_word: &'static [&'static str],
    pub tax: &'static [&'static str],
    pub tax_word: &'static [&'static str],
    pub base_salary: &'static [&'static str],
    pub currency: &'static str,
}

